def pct(x):
    return f"{100 * x:.2f}%"


def f4(x):
    return f"{x:.4f}"


def signed(x, nd=4):
    return f"{x:+.{nd}f}".replace("-", "−")


def case_table(R, key, case, title):
    lime = case["lime_top10"][:5]
    shap_rows = case["shap_top10"][:5]
    rows = []
    for i in range(5):
        rows.append([str(i + 1), lime[i]["rule"].replace("<=", "≤"), signed(lime[i]["weight"]),
                     f"{shap_rows[i]['feature']} = {shap_rows[i]['value']:g}", signed(shap_rows[i]["shap_value"])])
    R.table(key, title, ["Rank", "LIME condition", "LIME weight", "SHAP feature = value", "SHAP value"], rows,
            [0.55, 2.0, 0.8, 1.85, 0.8], align=["c", "l", "r", "l", "r"])


