def read_lines(rel):
    return (PROJ / rel).read_text(encoding="utf-8").splitlines()


def func_source(rel, name):
    """Top-level function or class source (decorators included) exactly as in the file."""
    lines = read_lines(rel)
    start = next(i for i, l in enumerate(lines) if re.match(rf"(def|class) {re.escape(name)}\b", l))
    while start > 0 and lines[start - 1].startswith("@"):
        start -= 1
    end = start + 1
    while end < len(lines) and not re.match(r"(def |class |@|[A-Za-z_]+\s*=|# -{5,})", lines[end]):
        end += 1
    block = lines[start:end]
    while block and not block[-1].strip():
        block.pop()
    return block, start + 1


def between(rel, start_marker, end_marker, include_end=False):
    lines = read_lines(rel)
    s = next(i for i, l in enumerate(lines) if start_marker in l)
    e = next(i for i in range(s + 1, len(lines)) if end_marker in lines[i])
    return lines[s:e + (1 if include_end else 0)], s + 1


def code_from(R, rel, name=None, start=None, end=None, include_end=False, what=""):
    if name:
        block, ln = func_source(rel, name)
    else:
        block, ln = between(rel, start, end, include_end)
    label = f"Code excerpt {R.chapter}.{R.code_n + 1} — `{rel}`, lines {ln}–{ln + len(block) - 1}" + (f": {what}" if what else "")
    R.code(block, label)


